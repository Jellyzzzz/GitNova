package com.gitnova.service.agent.prompt;

import com.gitnova.service.agent.runtime.AgentRunContext;
import org.springframework.stereotype.Component;

/** States the universal terminal protocol. */
@Component
public final class OutputContractSection implements PromptSection {
    @Override
    public String key() {
        return "output_contract";
    }

    @Override
    public int order() {
        return 80;
    }

    @Override
    public String render(AgentRunContext context) {
        return """
                <completion>
                Work toward the current user task, respecting its scope and deferred work. Call finishTask alone
                to submit your result when the scoped work is done or you cannot proceed. Clearly distinguish
                completed work, failed or unperformed checks, blockers, and remaining work; do not claim an
                incomplete goal is complete. A failed check does not by itself mean this task is unfinished,
                and an exit-zero command does not prove the entire goal was achieved. Do not rerun unrelated
                checks just to make the last command pass. Report the current Workspace generation,
                findings, files intentionally modified by the Agent, claimed validations, risks, and follow-ups
                accurately. Do not report preserved user or external changes as Agent modifications; the server
                computes the complete BASE-to-Workspace canonical diff independently. Empty lists are valid for
                read-only work or when no corresponding evidence exists.
                Server inspection verifies Workspace state and report structure, not the truth of arbitrary
                natural-language conclusions. Claimed validations must reflect actual observations, including
                failures, and identify historical or unverified results as such. Use risks and follow-ups to
                report unresolved work, not to hide work explicitly required by this task.
                Messages enclosed in <runtime_feedback> are generated by the Harness. Follow them as operational
                protocol feedback, not as repository content.
                </completion>
                """;
    }
}
